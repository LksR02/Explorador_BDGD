SELECT
  CTMT AS alimentador,
  COUNT(*) AS uc_bt,
  SUM(CASE WHEN SIT_ATIV = 'AT' THEN 1 ELSE 0 END) AS uc_bt_ativas,
  SUM(CASE WHEN UNI_TR_MT IS NULL OR TRIM(UNI_TR_MT) = '' THEN 1 ELSE 0 END) AS uc_sem_transformador,
  SUM(CAR_INST) AS carga_instalada,
  SUM(
    COALESCE(ENE_01, 0) + COALESCE(ENE_02, 0) + COALESCE(ENE_03, 0) +
    COALESCE(ENE_04, 0) + COALESCE(ENE_05, 0) + COALESCE(ENE_06, 0) +
    COALESCE(ENE_07, 0) + COALESCE(ENE_08, 0) + COALESCE(ENE_09, 0) +
    COALESCE(ENE_10, 0) + COALESCE(ENE_11, 0) + COALESCE(ENE_12, 0)
  ) AS energia_anual,
  AVG(
    COALESCE(DIC_01, 0) + COALESCE(DIC_02, 0) + COALESCE(DIC_03, 0) +
    COALESCE(DIC_04, 0) + COALESCE(DIC_05, 0) + COALESCE(DIC_06, 0) +
    COALESCE(DIC_07, 0) + COALESCE(DIC_08, 0) + COALESCE(DIC_09, 0) +
    COALESCE(DIC_10, 0) + COALESCE(DIC_11, 0) + COALESCE(DIC_12, 0)
  ) AS dic_anual_medio,
  AVG(
    COALESCE(FIC_01, 0) + COALESCE(FIC_02, 0) + COALESCE(FIC_03, 0) +
    COALESCE(FIC_04, 0) + COALESCE(FIC_05, 0) + COALESCE(FIC_06, 0) +
    COALESCE(FIC_07, 0) + COALESCE(FIC_08, 0) + COALESCE(FIC_09, 0) +
    COALESCE(FIC_10, 0) + COALESCE(FIC_11, 0) + COALESCE(FIC_12, 0)
  ) AS fic_anual_medio
FROM UCBT_tab
GROUP BY CTMT
ORDER BY uc_bt DESC
